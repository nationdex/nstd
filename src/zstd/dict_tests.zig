test "formatted dictionary: decode a frame made by the reference encoder" {
    const a = std.testing.allocator;
    const out = try dec.decompressDict(a, ref_frame, tiny_dict);
    defer a.free(out);
    try std.testing.expectEqualSlices(u8, sample, out);
    // Without the dictionary the frame must be rejected, not misdecoded.
    try std.testing.expect(std.meta.isError(dec.decompress(a, ref_frame)));
}

test "formatted dictionary: our frames use the dictionary id and round trip" {
    const a = std.testing.allocator;
    const d = try dict_mod.Dict.init(tiny_dict);
    try std.testing.expect(d.is_formatted);
    for ([_]i32{ 1, 3, 9 }) |lvl| {
        const z = try comp.compressDictLevel(a, sample, tiny_dict, lvl);
        defer a.free(z);
        const out = try dec.decompressDict(a, z, tiny_dict);
        defer a.free(out);
        try std.testing.expectEqualSlices(u8, sample, out);
        const plain = try comp.compressLevel(a, sample, lvl);
        defer a.free(plain);
        try std.testing.expect(z.len <= plain.len);
    }
}

test "damaged dictionaries never panic" {
    const a = std.testing.allocator;
    var prng = std.Random.DefaultPrng.init(0xD1C7);
    const rng = prng.random();
    const m = try a.dupe(u8, tiny_dict);
    defer a.free(m);
    for (0..400) |_| {
        @memcpy(m, tiny_dict);
        for (0..rng.uintLessThan(usize, 4) + 1) |_| m[rng.uintLessThan(usize, m.len)] = rng.int(u8);
        if (dec.decompressDict(a, ref_frame, m)) |o| a.free(o) else |_| {}
        if (comp.compressDictLevel(a, sample, m, 3)) |z| a.free(z) else |_| {}
        // truncated dictionary
        const cut = rng.uintLessThan(usize, m.len);
        if (dec.decompressDict(a, ref_frame, m[0..cut])) |o| a.free(o) else |_| {}
    }
